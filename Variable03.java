public class Variable03 {
    public static void main(String[] args) {
        // Deklarasi Variable
        String nama1, nama2, nama3, nama4;
        int NIM1, NIM2, NIM3, NIM4;
        
        // Isi Nilai Variable
        nama1 = "Gracia Wasis P.H.";
        nama2 = "Naila";
        nama3 = "Griselda";
        nama4 = "Siti Tasya";
        NIM1 = 123456;
        NIM2 = 456789;
        NIM3 = 678901;
        NIM4 = 890123;
        System.out.println("================================");
        System.out.println("NIM    |    Nama");
        System.out.println("================================");
        System.out.println(NIM1 + " | " + nama1);
        System.out.println(NIM2 + " | " + nama2);
        System.out.println(NIM3 + " | " + nama3);
        System.out.println(NIM4 + " | " + nama4);
        System.out.println("================================");
    }
}
