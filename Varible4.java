public class Varible4 {
    public static void main(String[] args) {
        int bilangan1, bilangan2;
        
        bilangan1 = 10;
        bilangan2 = 5;

        System.out.println("Bilangan 1 = " + bilangan1);
        System.out.println("Bilangan 2 = " + bilangan2);
        System.out.println("Hasil Tambah : " + (bilangan1 + bilangan2));
        System.out.println("Hasil Kurang : " + (bilangan1 - bilangan2));
        System.out.println("Hasil Kali : " + (bilangan1 * bilangan2));
        System.out.println("Hasil Bagi : " + (bilangan1 / bilangan2));
    }
}
